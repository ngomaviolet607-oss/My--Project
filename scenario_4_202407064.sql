CREATE OR REPLACE PROCEDURE clinic_lab.show_low_stock()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT medicine_name, stock_quantity
        FROM clinic_lab.medicines
        WHERE stock_quantity <= 5
        ORDER BY medicine_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Below low-stock threshold: % (% remaining)',
            v_item.medicine_name, v_item.stock_quantity;
    END LOOP;
    CLOSE c_low;
END;
$$;


CREATE OR REPLACE PROCEDURE clinic_lab.reverse_dispensing(p_record_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_medicine_id integer;
    v_quantity integer;
BEGIN
    SELECT medicine_id, quantity
    INTO v_medicine_id, v_quantity
    FROM clinic_lab.dispensing_records
    WHERE record_id = p_record_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active dispensing record with ID %', p_record_id;
        RETURN;
    END IF;

    UPDATE clinic_lab.dispensing_records
    SET status = 'REVERSED' WHERE record_id = p_record_id;

    UPDATE clinic_lab.medicines
    SET stock_quantity = stock_quantity + v_quantity
    WHERE medicine_id = v_medicine_id;

    RAISE NOTICE 'Dispensing % reversed; % units restored',
        p_record_id, v_quantity;
END;
$$;


CREATE OR REPLACE PROCEDURE library_lab.show_low_copies()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_low CURSOR FOR
        SELECT book_title, available_copies
        FROM library_lab.books
        WHERE available_copies <= 2
        ORDER BY book_id;
BEGIN
    OPEN c_low;
    LOOP
        FETCH c_low INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Few copies remaining: % (% remaining)',
            v_item.book_title, v_item.available_copies;
    END LOOP;
    CLOSE c_low;
END;
$$;


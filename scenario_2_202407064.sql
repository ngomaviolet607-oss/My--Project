CREATE OR REPLACE PROCEDURE lab_reservations.show_few_workstations()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_few CURSOR FOR
        SELECT session_name, available_workstations
        FROM lab_reservations.lab_sessions
        WHERE available_workstations <= 2
        ORDER BY session_id;
BEGIN
    OPEN c_few;
    LOOP
        FETCH c_few INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Few workstations left: % (% remaining)',
            v_item.session_name, v_item.available_workstations;
    END LOOP;
    CLOSE c_few;
END;
$$;


CREATE OR REPLACE PROCEDURE lab_reservations.reserve_workstations(
    p_session_id integer,
    p_lecturer text,
    p_workstations integer
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available integer;
    v_reservation_id integer;
BEGIN
    IF p_workstations <= 0 THEN
        RAISE EXCEPTION 'Workstations requested must be positive'
            USING ERRCODE = '22023';
    END IF;

    SELECT available_workstations INTO v_available
    FROM lab_reservations.lab_sessions
    WHERE session_id = p_session_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'Session % does not exist', p_session_id;
        RETURN;
    ELSIF v_available < p_workstations THEN
        RAISE NOTICE 'Insufficient workstations: only % available', v_available;
        RETURN;
    END IF;

    UPDATE lab_reservations.lab_sessions
    SET available_workstations = available_workstations - p_workstations
    WHERE session_id = p_session_id;

    INSERT INTO lab_reservations.reservations
        (session_id, lecturer, workstations, status)
    VALUES (p_session_id, p_lecturer, p_workstations, 'ACTIVE')
    RETURNING reservation_id INTO v_reservation_id;

    RAISE NOTICE 'Reservation % created for lecturer %',
        v_reservation_id, p_lecturer;
END;
$$;

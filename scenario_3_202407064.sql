CREATE OR REPLACE PROCEDURE hostel_lab.check_out(p_allocation_id integer)
LANGUAGE plpgsql
AS $$
DECLARE
    v_room_id integer;
BEGIN
    SELECT room_id
    INTO v_room_id
    FROM hostel_lab.allocations
    WHERE allocation_id = p_allocation_id AND status = 'ACTIVE'
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE NOTICE 'No active allocation with ID %', p_allocation_id;
        RETURN;
    END IF;

    UPDATE hostel_lab.allocations
    SET status = 'CHECKED_OUT' WHERE allocation_id = p_allocation_id;

    UPDATE hostel_lab.hostel_rooms
    SET available_spaces = available_spaces + 1
    WHERE room_id = v_room_id;

    RAISE NOTICE 'Allocation % checked out; one space released',
        p_allocation_id;
END;
$$;

CALL hostel_lab.check_out(1);

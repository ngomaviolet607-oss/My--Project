CREATE OR REPLACE PROCEDURE hostel_lab.show_full_or_nearly_full()
LANGUAGE plpgsql
AS $$
DECLARE
    v_item record;
    c_full CURSOR FOR
        SELECT room_number, available_spaces
        FROM hostel_lab.hostel_rooms
        WHERE available_spaces <= 1
        ORDER BY room_id;
BEGIN
    OPEN c_full;
    LOOP
        FETCH c_full INTO v_item;
        EXIT WHEN NOT FOUND;
        RAISE NOTICE 'Full or nearly full room: % (% spaces left)',
            v_item.room_number, v_item.available_spaces;
    END LOOP;
    CLOSE c_full;
END;
$$;

